#!/bin/sh
# Scheme pre-action: turns the Google values passed with
# `--dart-define-from-file=env/<env>.json` into Xcode build settings, so
# Info.plist (GIDClientID, URL scheme) reads them from the same env file.
# Writes Flutter/DartDefines.xcconfig (gitignored).

flutter_dir="${SRCROOT:-$(dirname "$0")/..}/Flutter"
out="$flutter_dir/DartDefines.xcconfig"
defines=$(sed -n 's/^DART_DEFINES=//p' "$flutter_dir/Generated.xcconfig" 2>/dev/null)

{
  echo "// Generated by ios/scripts/dart_defines.sh. Do not edit."
  for encoded in $(echo "$defines" | tr ',' ' '); do
    pair=$(echo "$encoded" | base64 --decode 2>/dev/null)
    case "$pair" in
      GOOGLE_IOS_CLIENT_ID=?*)
        client_id=${pair#GOOGLE_IOS_CLIENT_ID=}
        echo "GOOGLE_IOS_CLIENT_ID = $client_id"
        echo "GOOGLE_REVERSED_CLIENT_ID = com.googleusercontent.apps.${client_id%.apps.googleusercontent.com}"
        ;;
    esac
  done
} > "$out"
